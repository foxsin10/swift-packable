import Foundation

/// One dependency from `packable.yml`, resolved for the current mode.
public struct SwitchedDependency: Sendable, Equatable {
  public init(
    name: String,
    mode: PackableConfig.Mode,
    packageExpression: String,
    packageName: String
  ) {
    self.name = name
    self.mode = mode
    self.packageExpression = packageExpression
    self.packageName = packageName
  }

  /// The key in `packable.yml`, used as `packable(_:from:)`'s `from:` argument.
  public let name: String
  public let mode: PackableConfig.Mode
  /// A `Package.Dependency` expression, e.g. `.package(path: "../Foo")`.
  public let packageExpression: String
  /// The package name `.product(name:package:)` needs in this mode.
  public let packageName: String
}

/// The generated region of a client's `Package.swift`, between `// packable:begin` and
/// `// packable:end`.
public enum ManifestBlock {
  public static let beginMarker = "// packable:begin"
  public static let endMarker = "// packable:end"

  /// - Parameter usesSharedCache: Declare `packableCache`, which paths of binaries built
  ///   on demand refer to, so the manifest is the same on every machine.
  public static func render(
    _ dependencies: [SwitchedDependency],
    usesSharedCache: Bool
  ) -> String {
    var lines = [
      beginMarker,
      "// Generated by `xcframework-packable generate` from packable.yml; don't edit by hand.",
      "// Switch modes with `xcframework-packable use source|binary <name>`.",
      // Formatters would otherwise rewrite the block, and the next `generate` undo it.
      "// swiftformat:disable all"
    ]
    let summary = dependencies.map { "\($0.name): \($0.mode.rawValue)" }
    if !summary.isEmpty {
      lines.append("// \(summary.joined(separator: ", "))")
    }
    if usesSharedCache {
      lines += [
        "let packableCache = Context.environment[\"XCFRAMEWORK_PACKABLE_CACHE\"]",
        "  ?? (Context.environment[\"HOME\"] ?? \"\") + \"/Library/Caches/xcframework-packable\""
      ]
    }

    lines.append("")
    lines.append("let packableDependencies: [Package.Dependency] = [")
    lines += dependencies.map { "  \($0.packageExpression)," }
    lines.append("]")
    lines.append("")
    lines += [
      "/// A product of a dependency declared in packable.yml, in its current mode.",
      "func packable(_ product: String, from dependency: String) -> Target.Dependency {",
      "  let packages: [String: String] = ["
    ]
    lines += dependencies
      .map { "    \(swiftLiteral($0.name)): \(swiftLiteral($0.packageName))," }
    if dependencies.isEmpty {
      lines[lines.count - 1] = "  let packages: [String: String] = [:]"
    } else {
      lines.append("  ]")
    }
    lines += [
      "  return .product(name: product, package: packages[dependency] ?? dependency)",
      "}",
      "// swiftformat:enable all",
      endMarker
    ]
    return lines.joined(separator: "\n")
  }

  /// Replaces the block in `manifest`, or inserts it after `import PackageDescription`.
  public static func splice(_ block: String, into manifest: String) throws -> String {
    var lines = manifest.components(separatedBy: "\n")
    let begin = lines
      .firstIndex { $0.trimmingCharacters(in: .whitespaces) == beginMarker }
    let end = lines.firstIndex { $0.trimmingCharacters(in: .whitespaces) == endMarker }

    switch (begin, end) {
    case let (begin?, end?) where begin < end:
      lines.replaceSubrange(begin ... end, with: [block])
    case (nil, nil):
      guard let importLine = lines.firstIndex(where: {
        $0.trimmingCharacters(in: .whitespaces) == "import PackageDescription"
      }) else {
        throw MakerError("Package.swift has no `import PackageDescription` line.")
      }
      lines.insert(contentsOf: ["", block], at: importLine + 1)
    default:
      let markers = "`\(beginMarker)` and `\(endMarker)`"
      throw MakerError("Package.swift must contain both \(markers), in that order.")
    }
    return lines.joined(separator: "\n")
  }
}
