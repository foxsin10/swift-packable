import Foundation

/// Renders a `Package.swift` that exposes the built XCFrameworks as binary targets,
/// with the same library products as the source package.
public enum BinaryManifest {
  public enum Location: Equatable, Sendable {
    case path(String)
    case remote(url: String, checksum: String)
  }

  public struct Product: Equatable, Sendable {
    public init(name: String, modules: [String]) {
      self.name = name
      self.modules = modules
    }

    public let name: String
    public let modules: [String]
  }

  public static func render(
    packageName: String,
    platforms: [PackageManifest.Platform],
    products: [Product],
    artifacts: [(module: String, location: Location)]
  ) -> String {
    var lines = [
      "// swift-tools-version:5.9",
      "// Generated by xcframework-packable. Binary distribution of \(packageName).",
      "import PackageDescription",
      "",
      "let package = Package(",
      "    name: \(literal(packageName)),"
    ]

    let renderedPlatforms = platforms.compactMap { platform in
      platformCase(platform.platformName).map { ".\($0)(\(literal(platform.version)))" }
    }
    if !renderedPlatforms.isEmpty {
      lines.append("    platforms: [\(renderedPlatforms.joined(separator: ", "))],")
    }

    lines.append("    products: [")
    for product in products {
      let name = literal(product.name)
      let targets = product.modules.map(literal).joined(separator: ", ")
      lines.append("        .library(name: \(name), targets: [\(targets)]),")
    }
    lines.append("    ],")

    lines.append("    targets: [")
    for artifact in artifacts {
      switch artifact.location {
      case let .path(path):
        let name = literal(artifact.module)
        lines.append("        .binaryTarget(name: \(name), path: \(literal(path))),")
      case let .remote(url, checksum):
        lines.append("        .binaryTarget(")
        lines.append("            name: \(literal(artifact.module)),")
        lines.append("            url: \(literal(url)),")
        lines.append("            checksum: \(literal(checksum))")
        lines.append("        ),")
      }
    }
    lines.append("    ]")
    lines.append(")")
    return lines.joined(separator: "\n") + "\n"
  }

  static func platformCase(_ manifestName: String) -> String? {
    [
      "macos": "macOS", "maccatalyst": "macCatalyst", "ios": "iOS", "tvos": "tvOS",
      "watchos": "watchOS", "visionos": "visionOS", "driverkit": "driverKit"
    ][manifestName.lowercased()]
  }

  private static func literal(_ string: String) -> String {
    let escaped = string
      .replacingOccurrences(of: "\\", with: "\\\\")
      .replacingOccurrences(of: "\"", with: "\\\"")
    return "\"\(escaped)\""
  }
}
