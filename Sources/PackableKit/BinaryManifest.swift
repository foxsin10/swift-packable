import Foundation

/// Renders a `Package.swift` that exposes the built XCFrameworks as binary targets,
/// with the same library products as the source package.
public enum BinaryManifest {
  public enum Location: Equatable, Sendable {
    case path(String)
    case remote(url: String, checksum: String)
  }

  public struct Product: Equatable, Sendable {
    public init(name: String, modules: [String]) {
      self.name = name
      self.modules = modules
    }

    public let name: String
    public let modules: [String]
  }

  /// - Parameter resourceCarriers: Modules with resources. Their binary target is renamed
  ///   and a carrier target installs the resource bundle. A dependency's carriers are in
  ///   a local package (`renderResourcePackage`), pulled in through a link target.
  public static func render(
    packageName: String,
    platforms: [PackageManifest.Platform],
    products: [Product],
    artifacts: [(module: String, location: Location)],
    defaultLocalization: String? = nil,
    resourceCarriers: [ResourceCarrier] = []
  ) -> String {
    let carriers = Dictionary(uniqueKeysWithValues: resourceCarriers
      .map { ($0.module, $0) })
    func binaryTargetName(_ module: String) -> String {
      carriers[module] == nil ? module : ResourceCarrier.binaryTargetName(for: module)
    }

    var lines = [
      "// swift-tools-version:5.9",
      "// Generated by swift-packable. Binary distribution of \(packageName).",
      "import PackageDescription",
      "",
      "let package = Package(",
      "    name: \(swiftLiteral(packageName)),"
    ]
    if let defaultLocalization {
      lines.append("    defaultLocalization: \(swiftLiteral(defaultLocalization)),")
    }

    lines += platformsLine(platforms)

    lines.append("    products: [")
    for product in products {
      var targets: [String] = []
      for module in product.modules {
        guard let carrier = carriers[module] else {
          targets.append(module)
          continue
        }
        targets.append(binaryTargetName(module))
        let installer = carrier.bundlePackage.map(ResourceCarrier.linkTargetName(for:))
          ?? carrier.target
        if !targets.contains(installer) {
          targets.append(installer)
        }
      }
      let list = targets.map(swiftLiteral).joined(separator: ", ")
      lines.append("        .library(name: \(swiftLiteral(product.name)), targets: [\(list)]),")
    }
    lines.append("    ],")

    let resourcePackages = Set(resourceCarriers.compactMap(\.bundlePackage)).sorted()
    if !resourcePackages.isEmpty {
      lines.append("    dependencies: [")
      for package in resourcePackages {
        let path = swiftLiteral(ResourceCarrier.packageFolder(for: package))
        lines.append("        .package(path: \(path)),")
      }
      lines.append("    ],")
    }

    lines.append("    targets: [")
    for artifact in artifacts {
      let name = swiftLiteral(binaryTargetName(artifact.module))
      switch artifact.location {
      case let .path(path):
        lines.append("        .binaryTarget(name: \(name), path: \(swiftLiteral(path))),")
      case let .remote(url, checksum):
        lines.append("        .binaryTarget(")
        lines.append("            name: \(name),")
        lines.append("            url: \(swiftLiteral(url)),")
        lines.append("            checksum: \(swiftLiteral(checksum))")
        lines.append("        ),")
      }
      if let carrier = carriers[artifact.module], carrier.bundlePackage == nil {
        lines += carrierTarget(carrier)
      }
    }
    for package in resourcePackages {
      let name = swiftLiteral(ResourceCarrier.linkTargetName(for: package))
      let identity = swiftLiteral(
        URL(fileURLWithPath: ResourceCarrier.packageFolder(for: package)).lastPathComponent
      )
      lines += [
        "        // Installs \(package)'s resource bundles, named after that package as its",
        "        // compiled Bundle.module expects.",
        "        .target(",
        "            name: \(name),",
        "            dependencies: [.product(name: \(name), package: \(identity))],",
        "            path: \(swiftLiteral(ResourceCarrier.linkPath(for: package))),",
        "            publicHeadersPath: \"include\"",
        "        ),"
      ]
    }
    lines.append("    ]")
    lines.append(")")
    return lines.joined(separator: "\n") + "\n"
  }

  /// The local package with the carriers of one dependency's modules. It has the
  /// dependency's name, so SwiftPM names the bundles as that package's code expects.
  public static func renderResourcePackage(
    name: String,
    platforms: [PackageManifest.Platform],
    defaultLocalization: String?,
    carriers: [ResourceCarrier]
  ) -> String {
    var lines = [
      "// swift-tools-version:5.9",
      "// Generated by swift-packable. Resource bundles of \(name)'s modules, whose code is",
      "// in the binary package.",
      "import PackageDescription",
      "",
      "let package = Package(",
      "    name: \(swiftLiteral(name)),"
    ]
    if let defaultLocalization {
      lines.append("    defaultLocalization: \(swiftLiteral(defaultLocalization)),")
    }
    lines += platformsLine(platforms)
    let product = swiftLiteral(ResourceCarrier.linkTargetName(for: name))
    let targets = carriers.map { swiftLiteral($0.target) }.joined(separator: ", ")
    lines.append("    products: [.library(name: \(product), targets: [\(targets)])],")
    lines.append("    targets: [")
    for carrier in carriers {
      lines += carrierTarget(carrier)
    }
    lines.append("    ]")
    lines.append(")")
    return lines.joined(separator: "\n") + "\n"
  }

  private static func platformsLine(_ platforms: [PackageManifest.Platform]) -> [String] {
    let rendered = platforms.compactMap { platform in
      platformCase(platform.platformName)
        .map { ".\($0)(\(swiftLiteral(platform.version)))" }
    }
    return rendered.isEmpty ? [] : ["    platforms: [\(rendered.joined(separator: ", "))],"]
  }

  static func platformCase(_ manifestName: String) -> String? {
    [
      "macos": "macOS", "maccatalyst": "macCatalyst", "ios": "iOS", "tvos": "tvOS",
      "watchos": "watchOS", "visionos": "visionOS", "driverkit": "driverKit"
    ][manifestName.lowercased()]
  }

  private static func carrierTarget(_ carrier: ResourceCarrier) -> [String] {
    let resources = carrier.resources.map { resource in
      let path = swiftLiteral(resource.path)
      switch (resource.rule, resource.localization) {
      case (.copy, _):
        return ".copy(\(path))"
      // Only these two are valid; SwiftPM reads a language from its .lproj folder.
      case let (_, localization?) where ["default", "base"].contains(localization):
        return ".process(\(path), localization: .\(localization))"
      default:
        return ".process(\(path))"
      }
    }
    return [
      "        // Carries \(carrier.module)'s resources: SwiftPM installs its resource bundle where",
      "        // the compiled Bundle.module looks for it. The code is in \(carrier.module)Binary.",
      "        .target(",
      "            name: \(swiftLiteral(carrier.target)),",
      "            path: \(swiftLiteral(carrier.path)),",
      "            resources: [\(resources.joined(separator: ", "))],",
      "            publicHeadersPath: \"include\"",
      "        ),"
    ]
  }
}
