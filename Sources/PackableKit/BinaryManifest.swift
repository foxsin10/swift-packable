import Foundation

/// Renders a `Package.swift` that exposes the built XCFrameworks as binary targets,
/// with the same library products as the source package.
public enum BinaryManifest {
  public enum Location: Equatable, Sendable {
    case path(String)
    case remote(url: String, checksum: String)
  }

  public struct Product: Equatable, Sendable {
    public init(name: String, modules: [String]) {
      self.name = name
      self.modules = modules
    }

    public let name: String
    public let modules: [String]
  }

  /// - Parameter resourceCarriers: Modules with resources. Their binary target is renamed
  ///   and a carrier target named after the module installs the resource bundle.
  public static func render(
    packageName: String,
    platforms: [PackageManifest.Platform],
    products: [Product],
    artifacts: [(module: String, location: Location)],
    defaultLocalization: String? = nil,
    resourceCarriers: [ResourceCarrier] = []
  ) -> String {
    let carriers = Dictionary(uniqueKeysWithValues: resourceCarriers
      .map { ($0.module, $0) })
    func binaryTargetName(_ module: String) -> String {
      carriers[module] == nil ? module : ResourceCarrier.binaryTargetName(for: module)
    }

    var lines = [
      "// swift-tools-version:5.9",
      "// Generated by swift-packable. Binary distribution of \(packageName).",
      "import PackageDescription",
      "",
      "let package = Package(",
      "    name: \(swiftLiteral(packageName)),"
    ]
    if let defaultLocalization {
      lines.append("    defaultLocalization: \(swiftLiteral(defaultLocalization)),")
    }

    let renderedPlatforms = platforms.compactMap { platform in
      platformCase(platform.platformName)
        .map { ".\($0)(\(swiftLiteral(platform.version)))" }
    }
    if !renderedPlatforms.isEmpty {
      lines.append("    platforms: [\(renderedPlatforms.joined(separator: ", "))],")
    }

    lines.append("    products: [")
    for product in products {
      let targets = product.modules
        .flatMap { carriers[$0] == nil ? [$0] : [binaryTargetName($0), $0] }
        .map(swiftLiteral)
        .joined(separator: ", ")
      let name = swiftLiteral(product.name)
      lines.append("        .library(name: \(name), targets: [\(targets)]),")
    }
    lines.append("    ],")

    lines.append("    targets: [")
    for artifact in artifacts {
      let name = swiftLiteral(binaryTargetName(artifact.module))
      switch artifact.location {
      case let .path(path):
        lines.append("        .binaryTarget(name: \(name), path: \(swiftLiteral(path))),")
      case let .remote(url, checksum):
        lines.append("        .binaryTarget(")
        lines.append("            name: \(name),")
        lines.append("            url: \(swiftLiteral(url)),")
        lines.append("            checksum: \(swiftLiteral(checksum))")
        lines.append("        ),")
      }
      if let carrier = carriers[artifact.module] {
        lines += carrierTarget(carrier)
      }
    }
    lines.append("    ]")
    lines.append(")")
    return lines.joined(separator: "\n") + "\n"
  }

  static func platformCase(_ manifestName: String) -> String? {
    [
      "macos": "macOS", "maccatalyst": "macCatalyst", "ios": "iOS", "tvos": "tvOS",
      "watchos": "watchOS", "visionos": "visionOS", "driverkit": "driverKit"
    ][manifestName.lowercased()]
  }

  private static func carrierTarget(_ carrier: ResourceCarrier) -> [String] {
    let resources = carrier.resources.map { resource in
      let path = swiftLiteral(resource.path)
      switch (resource.rule, resource.localization) {
      case (.copy, _):
        return ".copy(\(path))"
      case let (_, localization?):
        return ".process(\(path), localization: .\(localization))"
      default:
        return ".process(\(path))"
      }
    }
    return [
      "        // Carries \(carrier.module)'s resources: SwiftPM installs its resource bundle where",
      "        // the compiled Bundle.module looks for it. The code is in \(carrier.module)Binary.",
      "        .target(",
      "            name: \(swiftLiteral(carrier.module)),",
      "            path: \(swiftLiteral(carrier.path)),",
      "            resources: [\(resources.joined(separator: ", "))],",
      "            publicHeadersPath: \"include\"",
      "        ),"
    ]
  }
}
